"""Generate a professional compliance report PDF with ReportLab."""
from __future__ import annotations

import html
import io
from datetime import datetime, timezone


class ReportUnavailable(RuntimeError):
    """PDF generation is not available on this machine."""


def _escape(value) -> str:
    return html.escape(str(value if value is not None else ""))


def _paragraph_text(value, style_size: int | None = None) -> str:
    text = _escape(value).replace("\n", "<br/>")
    return text


def build_report(result: dict) -> bytes:
    try:
        from reportlab.lib import colors
        from reportlab.lib.pagesizes import A4
        from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
        from reportlab.lib.units import mm
        from reportlab.platypus import (
            HRFlowable,
            KeepTogether,
            Paragraph,
            SimpleDocTemplate,
            Spacer,
            Table,
            TableStyle,
        )
    except ImportError as exc:
        raise ReportUnavailable(
            "PDF reports require reportlab. Install it with: "
            "pip install -r requirements-app.txt"
        ) from exc

    dark = colors.HexColor("#1F3864")
    accent = colors.HexColor("#2C5CC5")
    muted = colors.HexColor("#5C6570")
    line = colors.HexColor("#DFE3E8")
    panel = colors.HexColor("#F5F7FA")
    green = colors.HexColor("#1F6034")
    green_bg = colors.HexColor("#EAF6EE")
    red = colors.HexColor("#8D2C24")
    red_bg = colors.HexColor("#FDECEB")
    amber = colors.HexColor("#7A5312")
    amber_bg = colors.HexColor("#FDF3E3")

    base = getSampleStyleSheet()
    title = ParagraphStyle(
        "ReportTitle", parent=base["Title"], fontName="Helvetica-Bold",
        fontSize=20, leading=24, textColor=dark, spaceAfter=2, alignment=0,
    )
    subtitle = ParagraphStyle(
        "ReportSubtitle", parent=base["Normal"], fontSize=9.5, leading=13,
        textColor=muted, spaceAfter=10,
    )
    heading = ParagraphStyle(
        "ReportHeading", parent=base["Heading2"], fontName="Helvetica-Bold",
        fontSize=12.5, leading=16, textColor=dark, spaceBefore=12, spaceAfter=6,
    )
    subheading = ParagraphStyle(
        "ReportSubheading", parent=base["Normal"], fontName="Helvetica-Bold",
        fontSize=10, leading=13, textColor=dark, spaceBefore=6, spaceAfter=3,
    )
    body = ParagraphStyle(
        "ReportBody", parent=base["Normal"], fontSize=9.5, leading=13.5,
        textColor=colors.HexColor("#1A1D21"), spaceAfter=5,
    )
    small = ParagraphStyle(
        "ReportSmall", parent=body, fontSize=8, leading=11, textColor=muted,
    )
    box_text = ParagraphStyle(
        "ReportBox", parent=body, fontSize=9, leading=13, spaceAfter=0,
    )

    document = result.get("document", {}) or {}
    violations = result.get("violations", []) or []
    verdict = str(result.get("verdict", "needs_review"))
    confidence = float(result.get("confidence", 0) or 0)
    errors = result.get("errors", []) or []
    trace = result.get("agent_trace", []) or []

    verdict_labels = {
        "compliant": "No compliance issue identified",
        "non_compliant": "Potential compliance issues identified",
        "needs_review": "Manual review required",
    }
    verdict_colours = {
        "compliant": (green, green_bg),
        "non_compliant": (red, red_bg),
        "needs_review": (amber, amber_bg),
    }
    verdict_ink, verdict_bg = verdict_colours.get(verdict, (amber, amber_bg))

    buffer = io.BytesIO()
    doc = SimpleDocTemplate(
        buffer,
        pagesize=A4,
        leftMargin=18 * mm,
        rightMargin=18 * mm,
        topMargin=18 * mm,
        bottomMargin=20 * mm,
        title="Financial Compliance Assessment Report",
        author="Financial Compliance Engine",
        subject="Prototype compliance analysis",
    )

    story = []
    story.append(Paragraph("Financial Compliance Assessment Report", title))
    story.append(Paragraph(
        "Generated by the multi-agent hybrid-RAG prototype on "
        f"{datetime.now(timezone.utc).strftime('%d %B %Y, %H:%M UTC')}. "
        "This document is a student prototype and is not legal, financial or "
        "compliance advice.",
        subtitle,
    ))
    story.append(HRFlowable(width="100%", thickness=0.8, color=line, spaceAfter=12))

    story.append(Table(
        [[Paragraph(
            f"<b>{_escape(verdict_labels.get(verdict, verdict))}</b><br/>"
            f"<font size=8>Confidence {confidence * 100:.0f}%</font>",
            ParagraphStyle(
                "Verdict", parent=body, textColor=verdict_ink,
                fontSize=11, leading=15, spaceAfter=0,
            ),
        )]],
        colWidths=[doc.width],
        style=TableStyle([
            ("BACKGROUND", (0, 0), (-1, -1), verdict_bg),
            ("BOX", (0, 0), (-1, -1), 0.8, verdict_ink),
            ("LEFTPADDING", (0, 0), (-1, -1), 10),
            ("RIGHTPADDING", (0, 0), (-1, -1), 10),
            ("TOPPADDING", (0, 0), (-1, -1), 8),
            ("BOTTOMPADDING", (0, 0), (-1, -1), 8),
        ]),
    ))
    story.append(Spacer(1, 10))

    meta_rows = [
        ["Document", document.get("filename", "-")],
        ["As-of date", document.get("as_of_date", "-")],
        ["Analysis mode", document.get("mode", "agents")],
        ["Characters analysed", document.get("characters", "-")],
        ["Segments analysed", document.get("segments_analyzed", "-")],
        ["Regulations retrieved", document.get("regulations_retrieved", "-")],
        ["Overall confidence", f"{confidence * 100:.0f}%"],
    ]
    meta_table = Table(
        [[Paragraph(f"<b>{_escape(label)}</b>", small),
          Paragraph(_paragraph_text(value), small)] for label, value in meta_rows],
        colWidths=[42 * mm, doc.width - 42 * mm],
        style=TableStyle([
            ("BACKGROUND", (0, 0), (0, -1), panel),
            ("GRID", (0, 0), (-1, -1), 0.4, line),
            ("VALIGN", (0, 0), (-1, -1), "TOP"),
            ("LEFTPADDING", (0, 0), (-1, -1), 6),
            ("RIGHTPADDING", (0, 0), (-1, -1), 6),
            ("TOPPADDING", (0, 0), (-1, -1), 4),
            ("BOTTOMPADDING", (0, 0), (-1, -1), 4),
        ]),
    )
    story.append(meta_table)

    story.append(Paragraph("Executive summary", heading))
    story.append(Paragraph(_paragraph_text(result.get("summary", "")), body))
    if errors:
        story.append(Paragraph(
            f"<b>{len(errors)} analysis note(s)</b> are recorded at the end of this report.",
            small,
        ))

    story.append(Paragraph("Detailed findings", heading))
    if not violations:
        story.append(Paragraph(
            "No violations were recorded for the analysed excerpts. Review the "
            "original document and the agent notes before relying on this result.",
            body,
        ))

    for index, violation in enumerate(violations, start=1):
        label = violation.get("category_label") or violation.get("category", "Issue")
        severity = str(violation.get("severity", "unknown")).upper()
        item_confidence = float(violation.get("confidence", 0) or 0)
        block = [Paragraph(
            f"{index}. {_escape(label)} &nbsp;&nbsp; "
            f"<font size=8 color='#8D2C24'>[{_escape(severity)}]</font> "
            f"<font size=8 color='#5C6570'>confidence {item_confidence * 100:.0f}%</font>",
            subheading,
        )]
        block.append(Paragraph(
            f"<b>Finding.</b> {_paragraph_text(violation.get('explanation', ''))}",
            body,
        ))

        snippet_table = Table(
            [[Paragraph(
                f"<b>Original snippet</b><br/>{_paragraph_text(violation.get('original_snippet', ''))}",
                box_text,
            )]],
            colWidths=[doc.width],
            style=TableStyle([
                ("BACKGROUND", (0, 0), (-1, -1), panel),
                ("BOX", (0, 0), (-1, -1), 0.5, line),
                ("LEFTPADDING", (0, 0), (-1, -1), 8),
                ("RIGHTPADDING", (0, 0), (-1, -1), 8),
                ("TOPPADDING", (0, 0), (-1, -1), 6),
                ("BOTTOMPADDING", (0, 0), (-1, -1), 6),
            ]),
        )
        block.append(snippet_table)
        block.append(Spacer(1, 5))

        fix_table = Table(
            [[Paragraph(
                f"<b>Suggested compliant wording</b><br/>"
                f"{_paragraph_text(violation.get('suggested_fix', ''))}",
                ParagraphStyle("Fix", parent=box_text, textColor=green),
            )]],
            colWidths=[doc.width],
            style=TableStyle([
                ("BACKGROUND", (0, 0), (-1, -1), green_bg),
                ("BOX", (0, 0), (-1, -1), 0.5, colors.HexColor("#A3D4B4")),
                ("LEFTPADDING", (0, 0), (-1, -1), 8),
                ("RIGHTPADDING", (0, 0), (-1, -1), 8),
                ("TOPPADDING", (0, 0), (-1, -1), 6),
                ("BOTTOMPADDING", (0, 0), (-1, -1), 6),
            ]),
        )
        block.append(fix_table)
        block.append(Spacer(1, 5))

        citation = violation.get("cited_regulation")
        if citation:
            citation_text = (
                f"<b>Cited regulation.</b> {_escape(citation.get('title', ''))}, "
                f"Section {_escape(citation.get('section', '-'))} "
                f"({_escape(citation.get('authority', ''))}). "
                f"Document ID {_escape(citation.get('doc_id', ''))}. "
                f"Effective {_escape(citation.get('effective_date', '-'))}; "
                f"last updated {_escape(citation.get('last_updated', '-'))}; "
                f"status {_escape(citation.get('status', '-'))}."
            )
            if citation.get("superseded_by"):
                citation_text += (
                    f" Superseded by {_escape(citation.get('superseded_by'))}"
                    f" on {_escape(citation.get('superseded_date', '-'))}."
                )
        else:
            citation_text = (
                "<b>Cited regulation.</b> None available. The finding is based on "
                "the model assessment alone and should be checked manually."
            )
        block.append(Paragraph(citation_text, small))
        story.append(Spacer(1, 4))
        story.append(KeepTogether(block))

    if errors:
        story.append(Paragraph("Analysis notes", heading))
        for error in errors:
            story.append(Paragraph(f"- {_paragraph_text(error)}", small))

    if trace:
        story.append(Paragraph("Agent trace", heading))
        for step in trace:
            story.append(Paragraph(f"- {_paragraph_text(step)}", small))

    story.append(Spacer(1, 10))
    story.append(HRFlowable(width="100%", thickness=0.8, color=line, spaceAfter=6))
    story.append(Paragraph(
        "<b>Disclaimer.</b> This is a student prototype. Its output is generated "
        "by a small fine-tuned language model with retrieval over a synthetic "
        "regulatory corpus, is not checked against current regulations, and is "
        "not legal, financial or compliance advice.",
        small,
    ))

    def footer(canvas, document_object):
        canvas.saveState()
        canvas.setFont("Helvetica", 7.5)
        canvas.setFillColor(muted)
        canvas.drawString(
            18 * mm, 11 * mm,
            "Financial Compliance Engine - prototype, not legal or financial advice",
        )
        canvas.drawRightString(
            A4[0] - 18 * mm, 11 * mm,
            f"Page {document_object.page}",
        )
        canvas.restoreState()

    doc.build(story, onFirstPage=footer, onLaterPages=footer)
    return buffer.getvalue()
