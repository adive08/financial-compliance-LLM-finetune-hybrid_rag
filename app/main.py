"""Web interface for the financial compliance engine.

    python app/main.py            # http://127.0.0.1:8000

The page starts cleanly with or without a trained adapter or a RAG index.
Document analysis runs through the multi-agent graph by default; set
PIPELINE_MODE=single to fall back to the Practical 1 single-model path.
"""
from __future__ import annotations

import importlib.util
import json
import os
import re
import sys

from fastapi import FastAPI, File, Form, Request, UploadFile
from fastapi.responses import HTMLResponse, JSONResponse, Response
from fastapi.templating import Jinja2Templates
from starlette.concurrency import run_in_threadpool

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.dirname(HERE))

from agents.pipeline import pipeline_mode, run_analysis          # noqa: E402
from app.extract import ExtractionError, extract_text            # noqa: E402
from app.inference import (MODEL, ModelUnavailable, adapter_present,  # noqa: E402
                           make_snippet)
from app.report import ReportUnavailable, build_report           # noqa: E402
from rag.retriever import index_status                           # noqa: E402

app = FastAPI(title="Financial Compliance Engine")
templates = Jinja2Templates(directory=os.path.join(HERE, "templates"))

DISCLAIMER = (
    "Prototype for coursework. Output is generated by a small fine-tuned "
    "language model with retrieval over a synthetic regulatory corpus, is not "
    "checked against current regulations, and is not legal, financial or "
    "compliance advice."
)


def base_context() -> dict:
    rag = index_status()
    return {
        "disclaimer": DISCLAIMER,
        "model_ready": adapter_present(),
        "index_ready": rag["ready"],
        "index_status": rag,
        "pipeline_mode": pipeline_mode(),
        "result": None,
        "result_json": "",
        "error": None,
        "snippet": None,
        "filename": None,
        "as_of_date": None,
    }


def render(request: Request, context: dict, status_code: int = 200):
    """Starlette >= 0.37 takes `request` first; keep that call in one place."""
    return templates.TemplateResponse(
        request=request, name="index.html", context=context, status_code=status_code)


@app.get("/", response_class=HTMLResponse)
async def index(request: Request):
    return render(request, base_context())


@app.get("/health")
async def health():
    rag = index_status()
    return JSONResponse({
        "status": "ok",
        "adapter_present": adapter_present(),
        "device": MODEL.device,
        "pipeline_mode": pipeline_mode(),
        "graph_backend": "langgraph" if importlib.util.find_spec("langgraph") else "sequential",
        "rag": rag,
    })


async def _extract_upload(document: UploadFile) -> str:
    blob = await document.read()
    return extract_text(document.filename, blob)


async def _run(text: str, filename: str | None, as_of_date: str | None):
    return await run_in_threadpool(run_analysis, text, filename, as_of_date)


@app.post("/analyze", response_class=HTMLResponse)
async def analyze(
    request: Request,
    document: UploadFile = File(...),
    as_of_date: str = Form(None),
):
    context = base_context()
    context["filename"] = document.filename
    context["as_of_date"] = as_of_date or None

    try:
        text = await _extract_upload(document)
    except ExtractionError as exc:
        context["error"] = str(exc)
        return render(request, context, status_code=400)

    context["snippet"] = make_snippet(text)
    try:
        result = await _run(text, document.filename, as_of_date)
    except ModelUnavailable as exc:
        context["error"] = str(exc)
        return render(request, context, status_code=503)
    except ValueError as exc:
        context["error"] = str(exc)
        return render(request, context, status_code=400)
    except Exception as exc:
        context["error"] = f"Analysis failed: {exc}"
        return render(request, context, status_code=500)

    context["result"] = result
    context["result_json"] = json.dumps(result, ensure_ascii=False)
    return render(request, context)


@app.post("/api/analyze")
async def api_analyze(
    document: UploadFile = File(...),
    as_of_date: str = Form(None),
):
    try:
        text = await _extract_upload(document)
        result = await _run(text, document.filename, as_of_date)
    except ExtractionError as exc:
        return JSONResponse({"error": str(exc)}, status_code=400)
    except ModelUnavailable as exc:
        return JSONResponse({"error": str(exc)}, status_code=503)
    except ValueError as exc:
        return JSONResponse({"error": str(exc)}, status_code=400)
    except Exception as exc:
        return JSONResponse({"error": f"Analysis failed: {exc}"}, status_code=500)
    return JSONResponse(result)


@app.post("/report")
async def report(payload: str = Form(...)):
    try:
        result = json.loads(payload)
    except json.JSONDecodeError:
        return JSONResponse({"error": "Invalid analysis payload."}, status_code=400)
    if not isinstance(result, dict) or "violations" not in result:
        return JSONResponse({"error": "Analysis payload is incomplete."}, status_code=400)

    try:
        pdf = await run_in_threadpool(build_report, result)
    except ReportUnavailable as exc:
        return JSONResponse({"error": str(exc)}, status_code=503)

    name = str((result.get("document") or {}).get("filename") or "document")
    safe = re.sub(r"[^A-Za-z0-9._-]+", "-", name).strip("-") or "document"
    safe = safe.rsplit(".", 1)[0]
    headers = {
        "Content-Disposition": f'attachment; filename="compliance-report-{safe}.pdf"'
    }
    return Response(content=pdf, media_type="application/pdf", headers=headers)


if __name__ == "__main__":
    import uvicorn

    uvicorn.run(app, host="127.0.0.1", port=int(os.environ.get("PORT", 8000)))
